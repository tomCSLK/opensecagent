#!/usr/bin/env python3
"""Writes THIRD-PARTY-LICENSES.txt: the licenses of everything built into the agent.

Covers the Rust crates that end up in a release build for Linux or Windows (normal dependencies only, no dev or
build dependencies). License texts are taken from the crate sources in the cargo registry and printed once per
distinct text.

Usage (from the repository root, after `cargo fetch`):
    python3 -I dev/third-party-licenses.py           # rewrite the file
    python3 -I dev/third-party-licenses.py --check   # exit 1 if the file is out of date
"""

import json
import pathlib
import re
import subprocess
import sys

TARGETS = [
    "x86_64-unknown-linux-gnu",
    "aarch64-unknown-linux-gnu",
    "x86_64-pc-windows-msvc",
    "aarch64-pc-windows-msvc",
]
OUTPUT = pathlib.Path("THIRD-PARTY-LICENSES.txt")
LICENSE_FILE = re.compile(r"^(licen[cs]e|copying|notice|unlicense)([-._].*)?$", re.IGNORECASE)


def metadata(target):
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return json.loads(out)


def shipped_packages(meta):
    """Packages reachable from the root over normal (runtime) dependency edges."""
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]
    seen, todo = set(), [root]
    while todo:
        current = todo.pop()
        for dep in nodes[current]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]) and dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                todo.append(dep["pkg"])
    return {i: packages[i] for i in seen}


def license_texts(package):
    folder = pathlib.Path(package["manifest_path"]).parent
    files = sorted(f for f in folder.iterdir() if f.is_file() and LICENSE_FILE.match(f.name))
    return [(f.name, f.read_text(encoding="utf-8", errors="replace").strip()) for f in files]


def add(texts, text, user):
    """Collects users per license text; texts differing only in whitespace count as one."""
    texts.setdefault(" ".join(text.split()), (text, []))[1].append(user)


def render():
    shipped = {}
    for target in TARGETS:
        shipped.update(shipped_packages(metadata(target)))
    crates = sorted(shipped.values(), key=lambda p: (p["name"].lower(), p["version"]))
    texts = {}  # whitespace-normalized text -> (text, list of "name version (file)")
    missing = []
    lines = [
        "Third-party software in opensecagent",
        "====================================",
        "",
        "Generated by dev/third-party-licenses.py from Cargo.lock for " + ", ".join(TARGETS) + ";",
        "do not edit by hand. A build for one system contains only the crates it needs.",
        "opensecagent itself is licensed under the GNU Affero General Public License, version 3 or later (see LICENSE).",
        "",
        f"Rust crates compiled into the program ({len(crates)})",
        "-" * 40,
    ]
    for p in crates:
        lines.append(f"{p['name']} {p['version']}: {p.get('license') or 'see license file'}"
                     + (f"  <{p['repository']}>" if p.get("repository") else ""))
        found = license_texts(p)
        if not found:
            missing.append(p)
        for name, text in found:
            add(texts, text, f"{p['name']} {p['version']} ({name})")

    if missing:
        lines += ["", "Crates without a license file in their source; their SPDX license applies:"]
        lines += [f"  {p['name']} {p['version']}: {p.get('license')}" for p in missing]

    lines += ["", "", "License texts", "=" * 40]
    for text, users in texts.values():
        lines += ["", "-" * 72, "Applies to:"]
        lines += [f"  {u}" for u in users]
        lines += ["-" * 72, "", text]
    return "\n".join(lines) + "\n"


def main():
    content = render()
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            print(f"{OUTPUT} is out of date; run dev/third-party-licenses.py", file=sys.stderr)
            sys.exit(1)
        return
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUTPUT} ({content.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
